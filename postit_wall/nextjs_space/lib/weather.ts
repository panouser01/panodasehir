// Map WMO weather code to our background logic
export function getWeatherBackground(code: number): string {
  if (code === 0) return 'sunny';
  if (code === 1 || code === 2 || code === 3) return 'cloudy';
  if (code >= 45 && code <= 48) return 'foggy';
  if (code >= 51 && code <= 67) return 'rainy';
  if (code >= 71 && code <= 77) return 'snowy';
  if (code >= 80 && code <= 82) return 'rainy';
  if (code >= 85 && code <= 86) return 'snowy';
  if (code >= 95) return 'storm';
  return 'sunny';
}

export function getWeatherConditionText(code: number): string {
  if (code === 0) return 'Güneşli';
  if (code === 1 || code === 2 || code === 3) return 'Parçalı Bulutlu';
  if (code >= 45 && code <= 48) return 'Sisli';
  if (code >= 51 && code <= 67) return 'Yağmurlu';
  if (code >= 71 && code <= 77) return 'Karlı';
  if (code >= 80 && code <= 82) return 'Sağanak Yağışlı';
  if (code >= 85 && code <= 86) return 'Kar Yağışlı';
  if (code >= 95) return 'Fırtınalı';
  return 'Açık';
}
